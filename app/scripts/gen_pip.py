"""Build app/src/components/pip-markup.gen.ts from Producer's Pip.

Run from the repository root:
    python3 -I app/scripts/gen_pip.py

The drawing comes from producer/scene/pip.py, unchanged. This script only:
- removes the SVG (SMIL) animations, because the page animates Pip with CSS
  so that state (a tap) and prefers-reduced-motion can control it;
- adds class names that the CSS in pip.tsx animates;
- prefixes the filter ids, so they do not clash with other ids on the page.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "producer" / "scene"))
from pip import pip  # noqa: E402  (producer/scene/pip.py, not the pip installer)
import parts  # noqa: E402

def body(pose):
    s = pip(134, 276, 1.0, "calm", pose)
    s = re.sub(r"<animateTransform\b.*?/>", "", s, flags=re.S)
    s = re.sub(r"<animate\b.*?/>", "", s, flags=re.S)
    s = re.sub(r"<g>\s*</g>", "", s)  # pip.py's blink group is empty once its animation is gone
    assert "animate" not in s
    # Breathing group: the painted body. Sway group around it: the wave.
    one(s, '<g filter="url(#paint)">')
    s = s.replace('<g filter="url(#paint)">',
                  '<g class="pip-sway"><g class="pip-breathe" filter="url(#paint)">')
    one(s, "   </g>\n  </g>\n </g>\n</g>")
    s = s.replace("   </g>\n  </g>\n </g>\n</g>", "   </g></g>\n  </g>\n </g>\n</g>")
    # Eyes: the whites and the pupils, so they can blink together.
    eyes = re.search(r'<g filter="url\(#ink\)">\s*<circle cx="106".*?<circle cx="1\d\d(?:\.\d+)?" cy="1[23]\d(?:\.\d+)?" r="[\d.]+" fill="#1A1A2E"/>\s*<circle[^>]*/>', s, flags=re.S)
    assert eyes, "eyes not found"
    s = s.replace(eyes.group(0), f'<g class="pip-eyes">{eyes.group(0)}</g>')
    return prefix(s)


def prefix(s):
    for name in ("paint", "ink", "fuzz"):
        s = s.replace(f'url(#{name})', f'url(#pip-{name})').replace(f'id="{name}"', f'id="pip-{name}"')
    return re.sub(r"\s+", " ", s).strip()


def one(s, needle):
    assert s.count(needle) == 1, needle


out = ROOT / "app" / "src" / "components" / "pip-markup.gen.ts"
out.write_text(
    "// Generated by app/scripts/gen_pip.py from producer/scene/pip.py. Do not edit.\n"
    f"export const PIP_DEFS = {json.dumps(prefix(parts.PAINT_FILTER))};\n"
    f"export const PIP_STAND = {json.dumps(body('stand'))};\n"
    f"export const PIP_WAVE = {json.dumps(body('wave'))};\n")
print(out)
